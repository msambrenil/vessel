type DeepString<T> = {
  [K in keyof T]: T[K] extends string ? string : DeepString<T[K]>;
};

export type TranslationType = DeepString<typeof TRANSLATIONS.es>;

export function getTranslations(lang: SupportedLanguage): TranslationType {
  return (TRANSLATIONS[lang] || TRANSLATIONS.es) as unknown as TranslationType;
}

export function formatDistance(meters: number, unitSystem: UnitSystem = "metric"): string {
  if (unitSystem === "imperial") {
    const feet = Math.round(meters * 3.28084);
    if (feet < 1000) {
      return `${feet} ft`;
    }
    const miles = (meters * 0.000621371).toFixed(1);
    return `${miles} mi`;
  }

  // Metric
  if (meters < 1000) {
    return `${Math.round(meters)} m`;
  }
  return `${(meters / 1000).toFixed(1)} km`;
}
